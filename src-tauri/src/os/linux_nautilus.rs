pub fn register_nautilus_script() -> Result<String, String> {
    let home = std::env::var("HOME").map_err(|e| e.to_string())?;
    let scripts_dir = std::path::PathBuf::from(home)
        .join(".local")
        .join("share")
        .join("nautilus")
        .join("scripts");
    std::fs::create_dir_all(&scripts_dir).map_err(|e| e.to_string())?;

    let exe_path = std::env::current_exe()
        .map(|p| p.to_string_lossy().to_string())
        .unwrap_or_else(|_| "raydrop".to_string());

    let script_path = scripts_dir.join("Send with Raydrop");
    let script_content = format!(
        "#!/usr/bin/env bash\n# Generated by Raydrop\nIFS=$'\\n'\nif [ -n \"$NAUTILUS_SCRIPT_SELECTED_FILE_PATHS\" ]; then\n    \"{exe}\" --send $NAUTILUS_SCRIPT_SELECTED_FILE_PATHS\nelse\n    \"{exe}\" --send \"$@\"\nfi\n",
        exe = exe_path
    );

    std::fs::write(&script_path, script_content).map_err(|e| e.to_string())?;

    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mut perms = std::fs::metadata(&script_path)
            .map_err(|e| e.to_string())?
            .permissions();
        perms.set_mode(0o755);
        std::fs::set_permissions(&script_path, perms).map_err(|e| e.to_string())?;
    }

    Ok(format!(
        "Nautilus script installed at {}",
        script_path.display()
    ))
}

pub fn set_linux_autostart(enabled: bool) -> Result<String, String> {
    let home = std::env::var("HOME").map_err(|e| e.to_string())?;
    let autostart_dir = std::path::PathBuf::from(home)
        .join(".config")
        .join("autostart");
    std::fs::create_dir_all(&autostart_dir).map_err(|e| e.to_string())?;
    let desktop_file = autostart_dir.join("raydrop.desktop");

    if enabled {
        let exe_path = std::env::current_exe()
            .map(|p| p.to_string_lossy().to_string())
            .unwrap_or_else(|_| "raydrop".to_string());
        let content = format!(
            "[Desktop Entry]\nType=Application\nName=Raydrop\nComment=Universal P2P File Transfer\nExec=\"{exe}\" --minimized\nTerminal=false\nX-GNOME-Autostart-enabled=true\n",
            exe = exe_path
        );
        std::fs::write(&desktop_file, content).map_err(|e| e.to_string())?;
        Ok("Linux XDG Autostart enabled.".to_string())
    } else {
        let _ = std::fs::remove_file(&desktop_file);
        Ok("Linux XDG Autostart disabled.".to_string())
    }
}

